#!/usr/bin/env python3
"""
Two diagnostics identified as untested by colleagues who read the draft.

(A) MISSINGNESS
    The eccentricity analysis uses each participant's own valid-node set.
    Nodes are dropped when they have fewer than --min-vertices-per-node
    vertices surviving the R2>30 pRF threshold. Threshold SWEEPS were already
    run, but a sweep does not test the thing that matters: whether validity
    itself depends on eccentricity.

    If peripheral nodes systematically fail the threshold, the surviving node
    set is not a random subset of visual cortex, and the eccentricity-
    controllability correlation could be partly generated by differential
    measurement availability rather than by biology.

    Test: within each participant, is node validity predicted by that node's
    eccentricity? Because eccentricity is only observed WHERE a node is valid,
    the group-mean eccentricity of each node (across participants who do have
    it) is used as the node-level predictor, and validity is the per-node
    outcome. Reported as a point-biserial correlation per participant, then
    tested at group level by sign-flip permutation.

    Also reports the simpler node-level summary: across nodes, the correlation
    between a node's mean eccentricity and the proportion of participants for
    whom it is valid.

(B) HEMISPHERE
    The Methods document a large right-greater-than-left asymmetry in raw
    average controllability that is specific to the visual network (whole-brain
    geometric mean ratio approximately 9.4). The manuscript then treats the
    eccentricity effect as a single bilateral relationship without testing it.

    Test: compute each participant's eccentricity-controllability partial
    correlation separately within the left and right visual nodes, then test
    the paired within-participant difference by sign-flip permutation. Same
    paired logic as run_division_slope_comparison.py, and for the same reason:
    a difference in significance between hemispheres is not a difference in
    effect.

Usage:
    python3 run_missingness_hemisphere.py \
        --prf-backbone-csv all_subjects_prf_backbone.csv \
        --controllability-csv "Received files/all_subjects_controllability_glasser.csv" \
        --atlas glasser --out-prefix missingness_hemisphere_glasser
    python3 run_missingness_hemisphere.py --self-test
"""
import argparse, csv, math, re, sys
from collections import defaultdict

import numpy as np
from scipy import stats

GLASSER_VIS_AREAS = {"V1","V2","V3","V4","V3A","V3B","V6","V6A","V7","IPS1",
                     "FFC","PIT","V8","VMV1","VMV2","VMV3","VVC",
                     "FST","LO1","LO2","LO3","MST","MT","PH","V3CD","V4t"}
GLASSER_RE = re.compile(r"^([LR])_(.+)_ROI$")
SCHAEFER_RE = re.compile(r"^7Networks_(LH|RH)_")


def is_vis_glasser(lab):
    m = GLASSER_RE.match(lab)
    return bool(m) and m.group(2) in GLASSER_VIS_AREAS


def hemi_of(lab, atlas):
    if atlas == "glasser":
        m = GLASSER_RE.match(lab); return m.group(1) if m else None
    m = SCHAEFER_RE.match(lab)
    return {"LH": "L", "RH": "R"}.get(m.group(1)) if m else None


def load_prf_with_validity(path, min_vertices_per_node, atlas):
    """Returns subj_ecc, node_size, and subj_valid[subject][node] = bool.
    Validity is recorded for EVERY visual node the atlas defines, so nodes that
    fail the threshold are represented as invalid rather than simply absent."""
    subj_ecc, node_size = defaultdict(dict), {}
    subj_valid = defaultdict(dict)
    with open(path, newline="") as f:
        for r in csv.DictReader(f):
            if r["atlas"] != atlas:
                continue
            vis = (r["is_vis_network"] == "True") if atlas == "schaefer200" else is_vis_glasser(r["backbone_label"])
            if not vis:
                continue
            lab, s = r["backbone_label"], r["subject"]
            node_size[lab] = int(r["n_vertices_total"])
            ok = (r["mean_eccentricity_deg"] != "" and
                  int(r["n_vertices_valid_R2gt30"]) >= min_vertices_per_node)
            subj_valid[s][lab] = ok
            if ok:
                subj_ecc[s][lab] = float(r["mean_eccentricity_deg"])
    return subj_ecc, node_size, subj_valid


def load_ctrl(path):
    avg, mod = defaultdict(dict), defaultdict(dict)
    with open(path, newline="") as f:
        for r in csv.DictReader(f):
            a = float(r["average_controllability"])
            mod[r["subject"]][r["node_label"]] = float(r["modal_controllability"])
            if a > 0:
                avg[r["subject"]][r["node_label"]] = math.log(a)
    return avg, mod


def partial_corr(x, y, z):
    x, y, z = map(lambda v: np.asarray(v, float), (x, y, z))
    if np.std(x) == 0 or np.std(y) == 0 or np.std(z) == 0:
        return np.nan
    rxy, rxz, ryz = stats.pearsonr(x, y)[0], stats.pearsonr(x, z)[0], stats.pearsonr(y, z)[0]
    den = math.sqrt((1 - rxz ** 2) * (1 - ryz ** 2))
    return np.nan if den == 0 or not np.isfinite(den) else (rxy - rxz * ryz) / den


def fz(r): return np.arctanh(np.clip(r, -0.999999, 0.999999))


def signflip(diff, n_perm, rng):
    diff = np.asarray(diff, float)
    obs = diff.mean()
    s = rng.choice([-1.0, 1.0], size=(n_perm, diff.size))
    null = (s * diff).mean(axis=1)
    return float(obs), float((np.sum(np.abs(null) >= abs(obs)) + 1) / (n_perm + 1))


# ------------------------------------------------------------- (A) missing --
def missingness_analysis(subj_valid, node_mean_ecc, n_perm, rng):
    per_subject = []
    for s, valid in subj_valid.items():
        nodes = [n for n in valid if n in node_mean_ecc]
        if len(nodes) < 8:
            continue
        v = np.array([1.0 if valid[n] else 0.0 for n in nodes])
        e = np.array([node_mean_ecc[n] for n in nodes])
        if v.std() == 0 or e.std() == 0:
            continue   # all valid or all invalid -> uninformative for this subject
        per_subject.append(stats.pearsonr(e, v)[0])
    if not per_subject:
        return None
    obs, p = signflip(fz(per_subject), n_perm, rng)
    return {"n_subjects": len(per_subject),
            "mean_point_biserial_r": float(np.tanh(obs)),
            "perm_p_value": p}


def node_level_validity(subj_valid, node_mean_ecc):
    nodes = sorted(set(node_mean_ecc) & set().union(*(set(v) for v in subj_valid.values())))
    prop = []
    ecc = []
    for n in nodes:
        vals = [subj_valid[s].get(n) for s in subj_valid if n in subj_valid[s]]
        if not vals:
            continue
        prop.append(np.mean([1.0 if v else 0.0 for v in vals]))
        ecc.append(node_mean_ecc[n])
    if len(prop) < 5:
        return None
    r, p = stats.pearsonr(ecc, prop)
    return {"n_nodes": len(prop), "r_ecc_vs_validity": float(r), "p_parametric": float(p)}


# ------------------------------------------------------------ (B) hemisphere --
def hemisphere_analysis(subj_ecc, subj_metric, node_size, atlas, min_nodes, n_perm, rng):
    per = {"L": {}, "R": {}}
    for s, e in subj_ecc.items():
        m = subj_metric.get(s, {})
        for h in ("L", "R"):
            common = sorted(n for n in (set(e) & set(m) & set(node_size)) if hemi_of(n, atlas) == h)
            if len(common) < min_nodes:
                continue
            r = partial_corr([e[n] for n in common], [m[n] for n in common],
                             [node_size[n] for n in common])
            if np.isfinite(r):
                per[h][s] = r
    shared = sorted(set(per["L"]) & set(per["R"]))
    if len(shared) < 5:
        return None, per
    d = fz([per["L"][s] for s in shared]) - fz([per["R"][s] for s in shared])
    obs, p = signflip(d, n_perm, rng)
    return {"n_paired": len(shared),
            "mean_r_left": float(np.tanh(fz([per["L"][s] for s in shared]).mean())),
            "mean_r_right": float(np.tanh(fz([per["R"][s] for s in shared]).mean())),
            "mean_z_difference_L_minus_R": obs, "perm_p_value": p}, per


# ---------------------------------------------------------------- self-test --
def self_test():
    rng = np.random.default_rng(0)
    print("1. missingness test detects eccentricity-dependent dropout")
    nodes = [f"n{i}" for i in range(20)]
    node_ecc = {n: float(i) for i, n in enumerate(nodes)}
    sv = {}
    for s in map(str, range(30)):
        # peripheral (high-eccentricity) nodes fail more often
        sv[s] = {n: (rng.random() > (node_ecc[n] / 25.0)) for n in nodes}
    res = missingness_analysis(sv, node_ecc, 2000, rng)
    assert res["perm_p_value"] < 0.01 and res["mean_point_biserial_r"] < -0.2, res
    print(f"   ok (r={res['mean_point_biserial_r']:+.3f}, p={res['perm_p_value']:.4f})")

    print("2. missingness test is null when dropout is eccentricity-independent")
    sv2 = {s: {n: (rng.random() > 0.3) for n in nodes} for s in map(str, range(30))}
    res2 = missingness_analysis(sv2, node_ecc, 2000, rng)
    assert res2["perm_p_value"] > 0.05, res2
    print(f"   ok (r={res2['mean_point_biserial_r']:+.3f}, p={res2['perm_p_value']:.3f})")

    print("3. hemisphere test detects a planted L/R difference")
    size = {}; ecc = {}; met = {}
    ln = [f"L_a{i}_ROI" for i in range(10)]; rn = [f"R_a{i}_ROI" for i in range(10)]
    for i, n in enumerate(ln + rn): size[n] = 100 + i   # must vary: it is the covariate
    for s in map(str, range(30)):
        e = {n: rng.normal(0, 1) for n in ln + rn}
        ecc[s] = e
        met[s] = {n: (0.9 if n.startswith("L") else 0.0) * e[n] + rng.normal(0, 0.4) for n in ln + rn}
    res3, _ = hemisphere_analysis(ecc, met, size, "glasser", 5, 2000, rng)
    assert res3["perm_p_value"] < 0.01 and res3["mean_r_left"] > res3["mean_r_right"], res3
    print(f"   ok (L={res3['mean_r_left']:+.3f} R={res3['mean_r_right']:+.3f}, p={res3['perm_p_value']:.4f})")

    print("4. hemisphere test is null when both hemispheres behave alike")
    for s in map(str, range(30)):
        e = ecc[s]
        met[s] = {n: 0.6 * e[n] + rng.normal(0, 0.4) for n in ln + rn}
    res4, _ = hemisphere_analysis(ecc, met, size, "glasser", 5, 2000, rng)
    assert res4["perm_p_value"] > 0.05, res4
    print(f"   ok (p={res4['perm_p_value']:.3f})")

    print("5. hemi_of parses both atlas conventions")
    assert hemi_of("L_V1_ROI", "glasser") == "L" and hemi_of("R_MT_ROI", "glasser") == "R"
    assert hemi_of("7Networks_LH_Vis_3", "schaefer200") == "L"
    print("   ok")
    print("\nSELF-TEST: ALL PASSED")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--prf-backbone-csv"); ap.add_argument("--controllability-csv")
    ap.add_argument("--atlas", default="glasser", choices=("schaefer200", "glasser"))
    ap.add_argument("--out-prefix")
    ap.add_argument("--min-nodes-per-hemisphere", type=int, default=6)
    ap.add_argument("--min-vertices-per-node", type=int, default=5)
    ap.add_argument("--n-permutations", type=int, default=10000)
    ap.add_argument("--seed", type=int, default=42)
    a = ap.parse_args()
    if a.self_test:
        self_test(); return
    for r in ("prf_backbone_csv", "controllability_csv", "out_prefix"):
        if not getattr(a, r): ap.error(f"--{r.replace('_','-')} is required")

    rng = np.random.default_rng(a.seed)
    subj_ecc, node_size, subj_valid = load_prf_with_validity(
        a.prf_backbone_csv, a.min_vertices_per_node, a.atlas)
    avg, mod = load_ctrl(a.controllability_csv)

    node_mean_ecc = {}
    for n in node_size:
        vals = [e[n] for e in subj_ecc.values() if n in e]
        if vals: node_mean_ecc[n] = float(np.mean(vals))

    rows = []
    print("=== (A) missingness: does node validity depend on eccentricity? ===")
    m = missingness_analysis(subj_valid, node_mean_ecc, a.n_permutations, rng)
    if m:
        print(f"  per-participant point-biserial r = {m['mean_point_biserial_r']:+.3f}, "
              f"p = {m['perm_p_value']:.4f} (n={m['n_subjects']})")
        rows.append({"analysis": "missingness_per_subject", "metric": "", "hemisphere": "",
                     "n": m["n_subjects"], "estimate": m["mean_point_biserial_r"],
                     "perm_p_value": m["perm_p_value"], "note": "negative r = peripheral nodes drop out more"})
    nl = node_level_validity(subj_valid, node_mean_ecc)
    if nl:
        print(f"  node-level: r(mean eccentricity, proportion valid) = {nl['r_ecc_vs_validity']:+.3f} "
              f"(parametric p = {nl['p_parametric']:.4f}, {nl['n_nodes']} nodes)")
        rows.append({"analysis": "missingness_node_level", "metric": "", "hemisphere": "",
                     "n": nl["n_nodes"], "estimate": nl["r_ecc_vs_validity"],
                     "perm_p_value": nl["p_parametric"], "note": "parametric p, node-level summary"})

    print("\n=== (B) hemisphere: does the effect differ L vs R? ===")
    for name, metric in (("average_controllability_log", avg), ("modal_controllability", mod)):
        res, per = hemisphere_analysis(subj_ecc, metric, node_size, a.atlas,
                                       a.min_nodes_per_hemisphere, a.n_permutations, rng)
        if res is None:
            print(f"  {name}: too few paired participants"); continue
        print(f"  {name:30s} L={res['mean_r_left']:+.3f} R={res['mean_r_right']:+.3f} "
              f"diff(z)={res['mean_z_difference_L_minus_R']:+.3f} p={res['perm_p_value']:.4f} "
              f"(n={res['n_paired']} paired)")
        rows.append({"analysis": "hemisphere_paired", "metric": name, "hemisphere": "L_minus_R",
                     "n": res["n_paired"], "estimate": res["mean_z_difference_L_minus_R"],
                     "perm_p_value": res["perm_p_value"],
                     "note": f"L r={res['mean_r_left']:+.3f}, R r={res['mean_r_right']:+.3f}"})

    out = f"{a.out_prefix}.csv"
    fields = ["analysis", "metric", "hemisphere", "n", "estimate", "perm_p_value", "note"]
    with open(out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields); w.writeheader()
        for r in rows: w.writerow({k: r.get(k, "") for k in fields})
    print(f"\nWritten to {out}")


if __name__ == "__main__":
    main()
